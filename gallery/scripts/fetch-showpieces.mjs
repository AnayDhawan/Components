#!/usr/bin/env node
/**
 * Fetch the gallery's curated showpieces from their real registries, at build time.
 *
 * This deliberately dogfoods the model the whole skill is built on: the repo
 * stores pointers, and the component is pulled live. Hand-copying the code into
 * gallery/src would make the gallery a vendored snapshot - exactly the thing
 * ATTRIBUTION.md says this project does not do, and it would silently go stale.
 *
 * Fetched files land in src/components/ and are gitignored.
 *
 *   node scripts/fetch-showpieces.mjs
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const GALLERY = join(HERE, "..");
const REPO = join(GALLERY, "..");

/**
 * The live-fetched sample. Not every one of the 39 showpieces: this is a shop
 * window, not a catalogue, and every entry here is another upstream that can
 * break the deploy. Selection rules:
 *  - a spread across source libraries, weighted toward the cheapest dependency
 *    footprint (motion/CSS only - no WebGL, no three/ogl/gsap);
 *  - long-lived, popular entries unlikely to be renamed upstream.
 *
 * `texture-card` is listed because its upstream host is challenge-blocked for
 * automated clients (#31); it renders a hand-authored static preview (see
 * STATIC_DEMO). When #31 is resolved, move it out of STATIC_DEMO and update
 * DemoTextureCard to wrap the real component.
 */
const CURATED = [
  // aceternity
  "3d-card",
  "spotlight",
  "background-beams",
  // magicui
  "marquee",
  "shimmer-button",
  "meteors",
  "animated-shiny-text",
  "dock",
  // reactbits
  "blur-text",
  "count-up",
  "decrypted-text",
  // cult-ui - known-blocked, renders a static preview until #31 is resolved
  "texture-card",
  // 21st.dev (kokonutui mirror)
  "matrix-text",
];

/**
 * Effects rendered as hand-authored static previews instead of live fetches.
 * Either their upstream host blocks automation (#31, cult-ui) or they are
 * WebGL/canvas-class: rendering them live would mean several extra WebGL
 * contexts and a multi-megabyte bundle, the trade-off the CURATED comment
 * above was written to avoid. Static previews are self-contained CSS/SVG
 * approximations - no bundle weight, no upstream dependency, and every one of
 * them is guaranteed to render. See docs/previews-audit.md (F-5).
 */
const STATIC_PREVIEW = [
  "globe",
  "aurora",
  "particles-webgl",
  "hyperspeed",
  "splash-cursor",
  "shader-lens-blur",
  "cobe-globe-interactive",
  "letter-glitch",
  "canvas-fractal-grid",
];

/**
 * Every name in CURATED/STATIC_PREVIEW must have a hand-written demo component
 * named Demo<Name>.tsx in src/demos/, so a listing can never render as a bare
 * placeholder just because its demo was forgotten. This is the guard that
 * keeps the fetch list and the demo components from silently drifting (#62).
 */
function pascalName(name) {
  return name
    .split("-")
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
}

function demoFilePath(name) {
  return join(GALLERY, "src", "demos", `Demo${pascalName(name)}.tsx`);
}

function assertDemosExist(names) {
  for (const name of names) {
    const file = demoFilePath(name);
    if (!existsSync(file)) {
      console.error(
        `demo component missing for '${name}': expected ${relative(GALLERY, file)}. ` +
          "Every entry in CURATED/STATIC_PREVIEW needs a Demo<Name>.tsx.",
      );
      process.exit(1);
    }
  }
}

/**
 * Names whose visual is a hand-authored static preview. Mostly STATIC_PREVIEW
 * (WebGL/canvas-class effects), plus texture-card: its host is blocked (#31), so
 * no real component is available to wrap until that issue is resolved.
 */
const STATIC_DEMO = [...STATIC_PREVIEW, "texture-card"];

/**
 * Write src/demos/index.ts, the one place the app reads to know which demo
 * component renders each effect. Derived from CURATED/STATIC_PREVIEW here, so
 * the app's demo registry cannot drift from the fetch list (the exact bug #62
 * found: texture-card was fetched but had no registered demo). The file is
 * committed so `tsc` works before a fetch, and is overwritten identically
 * whenever the lists change.
 */
function generateDemoIndex() {
  const live = CURATED.filter((n) => !STATIC_DEMO.includes(n));
  const statics = STATIC_DEMO;
  const importLine = (n) => {
    const c = "Demo" + pascalName(n);
    return `import { ${c} } from "./${c}";`;
  };
  const lines = [
    "/* Generated by gallery/scripts/fetch-showpieces.mjs - do not edit by hand. */",
    'import type { ReactNode } from "react";',
    "",
    ...live.map(importLine),
    ...statics.map(importLine),
    "",
    "/** Live demos wrap the actually-fetched component (only render when available). */",
    "export const LIVE_DEMOS: Record<string, () => ReactNode> = {",
    ...live.map((n) => `  "${n}": ${"Demo" + pascalName(n)},`),
    "};",
    "",
    "/** Static previews are self-contained CSS/SVG approximations (render whenever listed). */",
    "export const STATIC_PREVIEWS: Record<string, () => ReactNode> = {",
    ...statics.map((n) => `  "${n}": ${"Demo" + pascalName(n)},`),
    "};",
    "",
  ];
  writeFileSync(join(GALLERY, "src", "demos", "index.ts"), lines.join("\n"));
}

/** Same allowlist discipline as scripts/smoke-test.mjs: refs are data, not commands. */
const ALLOWED_HOSTS = new Set([
  "ui.aceternity.com",
  "magicui.design",
  "www.cult-ui.com",
  "reactbits.dev",
  "kokonutui.com",
  "21st.dev",
]);

/**
 * Sourced from components.json's own `known_issues[]` at load time (see
 * main()), the same array scripts/health-check.py and scripts/smoke-test.mjs
 * read - one place to update instead of three hand-maintained copies.
 */
function knownBlockedHosts(data) {
  const out = {};
  for (const rec of data.known_issues ?? []) {
    out[rec.host] = `${rec.why} (#${rec.issue})`;
  }
  return out;
}

const NPX =
  process.platform === "win32"
    ? { file: process.execPath, prefix: [join(dirname(process.execPath), "node_modules", "npm", "bin", "npx-cli.js")] }
    : { file: "npx", prefix: [] };

/**
 * Read an entry's structured `fetch` object.
 *
 * This gallery renders React only, so it takes just `shadcn` refs; a Vue or
 * Svelte variant's CLI is rejected here rather than fetched into a React app.
 * Reads `fetch` rather than regex-parsing `ref`: `ref` is the display string,
 * and three consumers each parsing it was the duplication #47 called out.
 */
function parseRef(fetchSpec) {
  if (!fetchSpec || typeof fetchSpec !== "object") return { error: "no structured `fetch` object" };
  if (fetchSpec.method !== "registry_cli") return { error: "not a runnable registry command" };
  if (fetchSpec.cli !== "shadcn") return { error: `cli '${fetchSpec.cli}' is not React's shadcn` };
  let url;
  try {
    url = new URL(fetchSpec.url);
  } catch {
    return { error: `unparseable URL: ${fetchSpec.url}` };
  }
  if (url.protocol !== "https:") return { error: `not https: ${url.href}` };
  if (!ALLOWED_HOSTS.has(url.hostname)) return { error: `host not allowlisted: ${url.hostname}` };
  return { url };
}

function main() {
  const registry = JSON.parse(readFileSync(join(REPO, "components.json"), "utf8"));
  const byName = new Map(registry.showpiece.map((e) => [e.name, e]));
  const KNOWN_BLOCKED = knownBlockedHosts(registry);

  mkdirSync(join(GALLERY, "src", "components"), { recursive: true });

  // Every listed entry needs a demo component before we bother fetching, so a
  // rename loses its visual instead of silently regressing to a placeholder.
  assertDemosExist([...CURATED, ...STATIC_PREVIEW]);
  // Regenerate the demo registry the app reads, from the same lists.
  generateDemoIndex();

  const status = [];
  for (const name of CURATED) {
    const entry = byName.get(name);
    if (!entry) {
      console.error(`Curated entry '${name}' is not in components.json showpiece[].`);
      process.exit(1);
    }

    const host = (() => {
      try {
        return new URL(entry.fetch?.url ?? "").hostname;
      } catch {
        return null;
      }
    })();

    if (host && KNOWN_BLOCKED[host]) {
      // Not a build failure: the entry keeps its hand-authored static preview
      // (see STATIC_PREVIEW), so the gallery shows the effect instead of the
      // honest-placeholder path - useful whenever the block is in force.
      console.log(`skip  ${entry.library}/${name}: ${KNOWN_BLOCKED[host]}`);
      status.push({ ...pick(entry), available: false, preview: "static", reason: KNOWN_BLOCKED[host] });
      continue;
    }

    const parsed = parseRef(entry.fetch);
    if (parsed.error) {
      console.log(`skip  ${entry.library}/${name}: ${parsed.error}`);
      status.push({ ...pick(entry), available: false, reason: parsed.error });
      continue;
    }

    try {
      console.log(`fetch ${entry.library}/${name} -> ${parsed.url.href}`);
      execFileSync(NPX.file, [...NPX.prefix, "--yes", "shadcn@latest", "add", parsed.url.href, "--yes", "--overwrite"], {
        cwd: GALLERY,
        stdio: "pipe",
        encoding: "utf8",
        env: { ...process.env, CI: "1" },
      });
      status.push({ ...pick(entry), available: true });
    } catch (err) {
      const msg = (err.stderr || err.stdout || err.message || "").toString().trim().split("\n").slice(-3).join(" ");
      console.log(`skip  ${entry.library}/${name}: fetch failed - ${msg}`);
      status.push({ ...pick(entry), available: false, reason: "upstream fetch failed" });
    }
  }

  // WebGL/canvas-class effects never get fetched into the gallery, but they are
  // still listed so every one of them has a visible preview. They are marked
  // preview:"static" and the app renders the hand-authored approximation.
  for (const name of STATIC_PREVIEW) {
    const entry = byName.get(name);
    if (!entry) {
      console.error(`Static-preview entry '${name}' is not in components.json showpiece[].`);
      process.exit(1);
    }
    console.log(`static ${entry.library}/${name} -> static preview (no live fetch)`);
    status.push({
      ...pick(entry),
      available: false,
      preview: "static",
      reason: "WebGL/canvas-class effect shown as a hand-authored static preview (docs/previews-audit.md, F-5)",
    });
  }

  // The app reads this to know what actually made it in, so a blocked upstream
  // degrades to a placeholder rather than a broken import.
  writeFileSync(
    join(GALLERY, "src", "showpieces.json"),
    JSON.stringify({ generatedAt: new Date().toISOString(), entries: status }, null, 2) + "\n",
  );

  const ok = status.filter((s) => s.available).length;
  const staticCount = status.filter((s) => s.preview === "static").length;
  console.log(`\n${ok}/${CURATED.length} curated showpieces fetched (${status.length - staticCount - ok} placeholder), ${staticCount} static previews.`);

  // layouts[] are pointers/descriptions, not independently renderable, so there is
  // nothing to fetch - write the array straight through for the gallery's Layouts tab.
  writeFileSync(
    join(GALLERY, "src", "layouts.json"),
    JSON.stringify(registry.layouts ?? [], null, 2) + "\n",
  );
}

function pick(e) {
  return {
    name: e.name,
    library: e.library,
    effect: e.effect,
    aliases: e.aliases,
    license: e.license,
    deps: e.deps ?? [],
    ref: e.ref,
    preview: null,
  };
}

main();
